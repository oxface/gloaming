using System.Globalization;
using Gloaming.Samples.Wholesale.IntegrationTests.Scenarios.Cqrs;
using Gloaming.Samples.Wholesale.IntegrationTests.Scenarios.Cqrs.TenantIsolation;
using Microsoft.Extensions.DependencyInjection;
using Npgsql;

namespace Gloaming.Samples.Wholesale.IntegrationTests.Queries;

public sealed partial class TenantIsolationTests
{
    private static CancellationToken Token => TestContext.Current.CancellationToken;

    private async Task<ProofDatabase> CreateAsync(int poolSize = 1, bool initialize = true)
    {
        string admin = await postgres.CreateDatabaseAsync(Token);
        var original = new NpgsqlConnectionStringBuilder(admin);
        string suffix = Guid.NewGuid().ToString("N");
        string ownerRole = "rls_owner_" + suffix;
        string runtimeRole = "rls_runtime_" + suffix;
        string password = Guid.NewGuid().ToString("N");
        using var identifiers = new NpgsqlCommandBuilder();
        await using (var connection = new NpgsqlConnection(admin))
        {
            await connection.OpenAsync(Token);
            // Every interpolated role/database/password value is generated by this fixture,
            // never consumer input. Real demo credentials are independently provisioned.
            await CommandAsync(
                connection,
                null,
                $"""
                CREATE ROLE {identifiers.QuoteIdentifier(ownerRole)} LOGIN PASSWORD '{password}'
                    NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOINHERIT;
                CREATE ROLE {identifiers.QuoteIdentifier(runtimeRole)} LOGIN PASSWORD '{password}'
                    NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOINHERIT;
                GRANT CONNECT, CREATE ON DATABASE {identifiers.QuoteIdentifier(original.Database!)}
                    TO {identifiers.QuoteIdentifier(ownerRole)};
                GRANT CONNECT ON DATABASE {identifiers.QuoteIdentifier(original.Database!)}
                    TO {identifiers.QuoteIdentifier(runtimeRole)};
                """
            );
        }

        string owner = new NpgsqlConnectionStringBuilder(admin)
        {
            Username = ownerRole,
            Password = password,
            Pooling = false,
        }.ConnectionString;
        string runtime = new NpgsqlConnectionStringBuilder(admin)
        {
            Username = runtimeRole,
            Password = password,
            Pooling = true,
            MaxPoolSize = poolSize,
            ApplicationName = "tenant-isolation-" + suffix,
            CommandTimeout = 10,
        }.ConnectionString;
        var proof = new ProofDatabase(admin, owner, runtime, ownerRole, runtimeRole);
        try
        {
            if (initialize)
            {
                await TenantIsolationJourney.InitializeAsync(owner, runtime, Token);
                await SalesRowSecurity.VerifyRuntimeAsync(proof.Runtime, Token);
            }

            return proof;
        }
        catch
        {
            await proof.DisposeAsync();
            throw;
        }
    }

    private static async Task<int> CommandAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction,
        string sql,
        params NpgsqlParameter[] parameters
    )
    {
        await using var command = new NpgsqlCommand(sql, connection, transaction);
        command.Parameters.AddRange(parameters);
        return await command.ExecuteNonQueryAsync(Token);
    }

    private static async Task<T> ValueAsync<T>(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction,
        string sql,
        params NpgsqlParameter[] parameters
    )
    {
        await using var command = new NpgsqlCommand(sql, connection, transaction);
        command.Parameters.AddRange(parameters);
        object? value = await command.ExecuteScalarAsync(Token);
        return (T)Convert.ChangeType(value!, typeof(T), CultureInfo.InvariantCulture);
    }

    private static Task<string> SelectTenantAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        string tenant
    ) =>
        ValueAsync<string>(
            connection,
            transaction,
            "SELECT set_config('app.tenant_key', @tenant, true)",
            new NpgsqlParameter("tenant", tenant)
        );

    private static Task<int> CountAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction = null
    ) => ValueAsync<int>(connection, transaction, "SELECT count(*) FROM sales.draft_orders");

    private static async Task DeniedAsync(
        Func<Task> operation,
        string code = PostgresErrorCodes.InsufficientPrivilege
    )
    {
        var failure = await Assert.ThrowsAsync<PostgresException>(operation);
        Assert.Equal(code, failure.SqlState);
    }

    private sealed class ProofDatabase(
        string adminConnection,
        string ownerConnection,
        string runtimeConnection,
        string ownerRole,
        string runtimeRole
    ) : IAsyncDisposable
    {
        internal string AdminConnection { get; } = adminConnection;
        internal string OwnerConnection { get; } = ownerConnection;
        internal string RuntimeConnection { get; } = runtimeConnection;
        internal string OwnerRole { get; } = ownerRole;
        internal string RuntimeRole { get; } = runtimeRole;
        internal NpgsqlDataSource Runtime { get; } = NpgsqlDataSource.Create(runtimeConnection);

        internal ServiceProvider Provider(bool retry = false) =>
            TenantIsolationJourney.CreateRuntimeProvider(Runtime, retry);

        internal async Task AdminAsync(string sql)
        {
            await using var connection = new NpgsqlConnection(AdminConnection);
            await connection.OpenAsync(Token);
            await CommandAsync(connection, null, sql);
        }

        public async ValueTask DisposeAsync()
        {
            await Runtime.DisposeAsync();
            var settings = new NpgsqlConnectionStringBuilder(AdminConnection);
            string database = settings.Database!;
            settings.Database = "postgres";
            await using var connection = new NpgsqlConnection(settings.ConnectionString);
            await connection.OpenAsync(CancellationToken.None);
            using var identifiers = new NpgsqlCommandBuilder();
            await using (
                var dropDatabase = new NpgsqlCommand(
                    $"DROP DATABASE {identifiers.QuoteIdentifier(database)} WITH (FORCE)",
                    connection
                )
            )
                await dropDatabase.ExecuteNonQueryAsync(CancellationToken.None);

            await using var dropRoles = new NpgsqlCommand(
                $"""
                DROP ROLE {identifiers.QuoteIdentifier(RuntimeRole)};
                DROP ROLE {identifiers.QuoteIdentifier(OwnerRole)};
                """,
                connection
            );
            await dropRoles.ExecuteNonQueryAsync(CancellationToken.None);
        }
    }
}
